def sample(bg='white',collision=False):
    im=Image.new('RGB',(600,360),bg)
    draw=ImageDraw.Draw(im)
    draw.rectangle((50,70,540,230), fill=(35,95,155))
    if collision:draw.rectangle((280,280,599,359),fill=(180,35,40))
    out=BytesIO();im.save(out,format='PNG');return out.getvalue()


def raster(data):
    im=Image.open(BytesIO(data));im.load();return im.convert('RGB')


class FinishingTest(unittest.TestCase):
    def test_vertical_crop_preserves_width_and_content(self):
        raw=sample();cropped,status,_=finishing._trim_whitespace(raw)
        self.assertEqual(status,'ok');self.assertEqual(raster(cropped).size,(600,177))
        self.assertIsNone(ImageChops.difference(raster(raw).crop((0,62,600,239)),raster(cropped)).getbbox())
        # Coloured edge bands follow the same reference background detection.
        dark,status,_=finishing._trim_whitespace(sample((25,30,35)))
        self.assertEqual(status,'ok');self.assertEqual(raster(dark).size,(600,177))
        self.assertEqual(raster(dark).getpixel((0,0)),(25,30,35))

    def test_watermark_is_bottom_right_with_reference_colour_and_margin(self):
        raw=sample();out,status,_=finishing._add_watermark(raw,IMAGE_WATERMARK)
        self.assertEqual(status,'ok');before,after=raster(raw),raster(out)
        bbox=ImageChops.difference(before,after).getbbox()
        self.assertGreater(bbox[0],280);self.assertGreater(bbox[1],320)
        self.assertLessEqual(bbox[2],590);self.assertLessEqual(bbox[3],350)
        self.assertIn((150,150,150),{colour for count,colour in after.getcolors(after.width*after.height)})
        self.assertEqual(IMAGE_WATERMARK,'Generated by ScholarSeed AI')

    def test_collision_adds_background_without_overwriting_content(self):
        for bg in ('white',(20,25,30)):
            raw=sample(bg,True);out,status,_=finishing._add_watermark(raw,IMAGE_WATERMARK)
            self.assertEqual(status,'padded');before,after=raster(raw),raster(out)
            self.assertEqual(after.width,before.width);self.assertGreater(after.height,before.height)
            self.assertIsNone(ImageChops.difference(before,after.crop((0,0,before.width,before.height))).getbbox())
            if bg!='white':self.assertIn((210,210,210),{colour for count,colour in after.getcolors(after.width*after.height)})

    def test_transparency_and_blank_or_invalid_images(self):
        im=Image.new('RGBA',(600,360),(0,0,0,0));ImageDraw.Draw(im).rectangle((20,60,570,240),fill=(30,100,180,255))
        buf=BytesIO();im.save(buf,format='PNG')
        out,status,_=finishing._trim_whitespace(buf.getvalue())
        self.assertEqual(status,'ok');self.assertEqual(raster(out).getpixel((0,0)),(255,255,255))
        blank=BytesIO();Image.new('RGB',(600,360),'white').save(blank,format='PNG')
        self.assertEqual(finishing._trim_whitespace(blank.getvalue())[1],'bbox_none')
        self.assertEqual(finishing._add_watermark(b'not an image',IMAGE_WATERMARK)[1],'error')


    def test_failure_retries_only_unfinished_image(self):
        with tempfile.TemporaryDirectory() as tmp:
            ws=types.SimpleNamespace(root=Path(tmp),figures_dir=Path(tmp)/'figures')
            cfg={'model':'fixture','_stage':'figures_image'};item={'figure_id':'F1','_prompt':'Diagram'}
            attempts=[{'ok':True,'stage':'figures_image','model':'fixture','size':'1536x1024'}]
            with patch.object(generate_images,'_request_image',return_value=(sample(),'',attempts)) as request:
                with patch.object(generate_images,'_add_watermark',return_value=(b'bad','error','fixture failure')):
                    ok,error,extra=generate_images._generate_image(ws,cfg,item)
                self.assertFalse(ok);self.assertIn('watermark failed',error);self.assertFalse((ws.figures_dir/'F1.png').exists())
                item.update(extra);item['_generated']=False
                self.assertTrue(generate_images._generate_image(ws,cfg,item)[0]);self.assertEqual(request.call_count,2)
            with patch.object(generate_images,'_check_postprocess',side_effect=ImportError('Pillow')),patch.object(generate_images,'_request_image') as request:
                ok,err,_=generate_images._generate_image(ws,cfg,{'figure_id':'F2','_prompt':'Another diagram'})
                self.assertFalse(ok);request.assert_not_called()





