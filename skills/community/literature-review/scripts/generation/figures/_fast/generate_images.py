def _build_request(cfg: dict, prompt: str, size: str) -> dict:
    """Build the IdeaLab gpt-image request body."""
    backend = cfg.get("backend") or DEFAULT_BACKEND
    if backend != "openai_image":
        raise ValueError(
            f"Unsupported image backend {backend!r}; expected 'openai_image'."
        )
    body = {"model": cfg.get("model"), "prompt": prompt, "size": size}
    # `quality` and `size` are mandatory. `response_format` must not be sent:
    # this endpoint rejects it and returns b64_json regardless.
    body["quality"] = cfg.get("quality") or "high"
    body["output_format"] = "png"
    return body


def _error_text(payload, status: int) -> str:
    """The failure, from whichever error shape the gateway uses.

    OpenAI-protocol services answer `{"error": {...}}`. The IdeaLab gateway
    answers `{"success": false, "message": ..., "detailMessage": ...}` with no
    `error` key at all — and `detailMessage` is the field that says what is
    actually wrong. A client reading only `error` learns nothing from its 400s.
    """
    if isinstance(payload, dict):
        if payload.get("error") is not None:
            return f"http {status}: {str(payload['error'])[:300]}"
        parts = [str(payload[k]) for k in ("code", "message", "detailMessage")
                 if payload.get(k)]
        if parts:
            return f"http {status}: " + " | ".join(parts)[:300]
    return f"http {status}: {str(payload)[:300]}"


def _keepalive_socket_options() -> list[tuple[int, int, int]]:
    """Socket options for image calls that may wait minutes for a response.

    IdeaLab's gateway recommends enabling TCP keepalive and sending the first
    probe after 30 seconds so a request with no response bytes for more than
    90 seconds is not mistaken for a dead connection.  Linux calls the idle
    option ``TCP_KEEPIDLE``; macOS calls the same setting ``TCP_KEEPALIVE``.
    The numeric fallback mirrors the gateway's documented client example.

    This is transport liveness, not an operation deadline.  The independent
    httpx timeout below still stops a genuinely stalled request.
    """
    tcp_keepidle = getattr(
        socket, "TCP_KEEPIDLE", getattr(socket, "TCP_KEEPALIVE", 0x10)
    )
    return [
        (socket.SOL_SOCKET, socket.SO_KEEPALIVE, 1),
        (socket.IPPROTO_TCP, tcp_keepidle, IMAGE_TCP_KEEPIDLE_SEC),
    ]


def _image_http_transport(httpx):
    """Build the synchronous equivalent of the gateway's async example."""
    return httpx.HTTPTransport(
        trust_env=True,
        socket_options=_keepalive_socket_options(),
    )


def _read_image_stream(response,record,began,deadline):
    chunks=[]
    for data in response.iter_bytes():
        if time.monotonic()-began>deadline:raise TimeoutError('image response exceeded its operation deadline')
        chunks.append(data);record['response_bytes']=record.get('response_bytes',0)+len(data)
    raw=b''.join(chunks).decode('utf-8')
    if 'text/event-stream' not in response.headers.get('content-type',''):
        return json.loads(raw)
    completed=None
    for line in raw.splitlines():
        if not line.startswith('data:'):continue
        text=line[5:].strip()
        if text=='[DONE]':continue
        event=json.loads(text)
        if str(event.get('type','')).endswith('.completed'):
            completed=event if event.get('data') else {'data':[{'b64_json':event.get('b64_json'),'url':event.get('url')}],'usage':event.get('usage')}
        if event.get('type')=='error':raise ValueError('image stream reported an error')
    if completed is None:raise ValueError('image stream has no completion event')
    return completed


def _request_one(cfg: dict, prompt: str, size: str, attempts=None) -> tuple[bytes | None, str]:
    """One image from ONE provider, with retries. Returns (image_bytes, error).

    Raw httpx rather than the `openai` SDK so the IdeaLab error shape and
    `output_format` pass through without SDK normalisation.
    """
    import httpx

    url = (cfg.get("base_url") or "").rstrip("/") + "/images/generations"
    body = _build_request(cfg, prompt, size)
    headers = {"Authorization": f"Bearer {cfg.get('api_key')}",
               "Content-Type": "application/json"}
    timeout = float(cfg.get("timeout") or IMAGE_TIMEOUT_SEC)

    last = ""
    attempts = attempts if attempts is not None else []
    maximum = min(IMAGE_MAX_ATTEMPTS, max(1, int(cfg.get('max_attempts', IMAGE_MAX_ATTEMPTS))))
    for attempt in range(1, maximum + 1):
        began = time.monotonic()
        record = {'attempt': attempt, 'stage': cfg.get('_stage'), 'model': cfg.get('model'),
                  'size': size, 'ok': False, 'http_status': None, 'usage': None}
        last = ''
        try:
            transport = _image_http_transport(httpx)
            with httpx.Client(timeout=timeout, trust_env=True,
                              transport=transport,
                              follow_redirects=True) as client:
                with client.stream('POST',url,headers=headers,json=body) as resp:
                    record['http_status']=resp.status_code
                    payload=_read_image_stream(resp,record,began,float(cfg.get('request_deadline_sec',1800)))
                    if resp.status_code != 200:
                        last=_error_text(payload,resp.status_code)
                        if resp.status_code not in _RETRYABLE_STATUS:return None,last
                        raise httpx.HTTPError(last)
                record['usage'] = payload.get('usage')
                data = (payload.get("data") or [])
                if not data:
                    return None, f"no data[] in response: {str(payload)[:300]}"
                item = data[0]
                if item.get("b64_json"):
                    import base64
                    image_data = base64.b64decode(item['b64_json'])
                    record['ok'] = True
                    return image_data, ''
                img_url = item.get("url")
                if not img_url:
                    return None, f"no url and no b64_json: keys={sorted(item)}"
                # The URL is presigned and expires (86400s observed), so it is
                # fetched now and never stored.
                with client.stream('GET',img_url) as got:
                    got.raise_for_status()
                    data=b''.join(got.iter_bytes())
                record['ok'] = True
                return data, ''
        except Exception as e:  # noqa: BLE001
            last = last or f"{type(e).__name__} during image transport"
            retryable = (record['http_status'] in _RETRYABLE_STATUS or
                         record['http_status'] is None and isinstance(e, httpx.HTTPError))
            if not retryable:
                return None, last
        finally:
            record['elapsed_sec'] = round(time.monotonic() - began, 3)
            if not record['ok']:
                record['error'] = last or 'response contained no valid image'
            attempts.append(record)
            # Persist after each attempt, including failures before a later retry.
            if cfg.get('_attempt_log'):
                path = Path(cfg['_attempt_log'])
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(json.dumps(attempts, ensure_ascii=False, indent=2))
        if attempt < maximum:
            time.sleep(2 ** attempt)
    return None, f"{maximum} attempts: {last}"


def _request_image(cfg: dict, prompt: str, preset: str
                   ) -> tuple[bytes | None, str, list[dict]]:
    """Request one image from the configured IdeaLab stage."""
    backend = cfg.get("backend") or DEFAULT_BACKEND
    sizes = SIZE_PRESETS.get(backend)
    if sizes is None:
        error = f"unsupported image backend: {backend!r}"
        return None, error, [{"stage": cfg.get("_stage"), "model": cfg.get("model"),
                              "ok": False, "error": error}]
    size = sizes.get(preset, sizes[DEFAULT_SIZE_PRESET])
    attempts = []
    from runtime_model_client import runtime_image,RuntimeModelError
    started=time.monotonic()
    try:
        result=runtime_image(cfg,prompt,size)
    except RuntimeModelError as exc:
        attempts.append({'attempt':1,'stage':cfg.get('_stage'),'model':cfg.get('model'),'size':size,
                         'ok':False,'transport':'runtime','retry_owner':'runtime','code':exc.code,
                         'error':str(exc),'elapsed_sec':round(time.monotonic()-started,3)})
        if cfg.get('_attempt_log'):
            Path(cfg['_attempt_log']).write_text(json.dumps(attempts,ensure_ascii=False),encoding='utf-8')
        return None,exc.code+': '+str(exc),attempts
    if result is not None:
        data,metadata=result
        attempts.append({'attempt':1,'stage':cfg.get('_stage'),'model':cfg.get('model'),'size':size,
                         'ok':True,'transport':'runtime','retry_owner':'runtime',**metadata,
                         'elapsed_sec':round(time.monotonic()-started,3)})
        if cfg.get('_attempt_log'):
            Path(cfg['_attempt_log']).write_text(json.dumps(attempts,ensure_ascii=False),encoding='utf-8')
        return data,'',attempts
    data, error = _request_one(cfg, prompt, size, attempts)
    return data, error, attempts


def _generate_image(ws: Workspace, cfg: dict, item: dict
                    ) -> tuple[bool, str, dict]:
    """Complete an image task once; retry only unfinished tasks, no hash cache."""
    import uuid
    fid=item['figure_id'];dest=ws.figures_dir/f'{fid}.png'
    if item.get('_generated') and dest.is_file():
        return True,'',{'_image_meta':item.get('_image_meta',{})}
    try:_check_postprocess()
    except Exception as exc:return False,'image postprocessing unavailable: '+str(exc),{}
    from figure_contract import image_prompt
    preset=(item.get('_image_size') or DEFAULT_SIZE_PRESET).strip().lower()
    folder=ws.root/'_logs/llm'/('image-'+uuid.uuid4().hex);folder.mkdir(parents=True,exist_ok=True)
    prompt=image_prompt(item)
    (folder/'request.json').write_text(json.dumps({'figure_id':fid,'prompt':prompt,'size_preset':preset},ensure_ascii=False))
    png,error,attempts=_request_image({**cfg,'_attempt_log':str(folder/'attempts.json')},prompt,preset)
    if png is None:return False,error,{'_image_meta':{'attempts':attempts}}
    (folder/'response.png').write_bytes(png)
    png,trim_status,trim_reason=_trim_vertical(png)
    if trim_status not in ('ok','noop'):return False,'vertical crop failed: '+trim_reason,{}
    png,wm_status,wm_reason=_add_watermark(png,IMAGE_WATERMARK)
    if wm_status not in ('ok','padded'):return False,'watermark failed: '+wm_reason,{}
    dest.parent.mkdir(parents=True,exist_ok=True)
    temp=dest.with_suffix('.png.tmp');temp.write_bytes(png);temp.replace(dest)
    return True,'',{'_image_meta':{'attempts':attempts,'stage':cfg.get('_stage'),'model':cfg.get('model'),
        'bytes':len(png),'trim':{'status':trim_status,'detail':trim_reason},
        'watermark':{'status':wm_status,'detail':wm_reason,'text':IMAGE_WATERMARK}}}


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--concurrency", type=int, default=4,
                   help="How many images to request at once. Each takes 30-50s "
                        "and they are independent, so this is wall-clock that "
                        "does not have to be spent serially.")
    p.add_argument("--resume-only", action="store_true",
                   help="reuse successful early renders and do not repeat image-model "
                        "requests that already failed during plan-generate")
    args = p.parse_args()

    started = time.time()
    ws = Workspace()
    img_cfg = _image_config()
    log_script_start(ws, "generate_images",
                     image_generation=("enabled" if img_cfg else "disabled"),
                     image_provider=(img_cfg or {}).get("model"),
                     tcp_keepalive=True,
                     tcp_keepidle_sec=IMAGE_TCP_KEEPIDLE_SEC)

    worklist_path = ws.figures_worklist_path()
    if not worklist_path.exists():
        write_status(ws, "generate_images", "FAILED",
                     duration_sec=round(time.time() - started, 2),
                     message="figures_worklist.json not found.")
        return 2
    worklist = load_json(worklist_path)
    items = worklist["items"]

    if not items:
        write_status(ws, "generate_images", "SUCCESS",
                     duration_sec=round(time.time() - started, 2),
                     rendered=0, total=0, message="No figures requested.")
        return 0

    # Image-mode items must still carry a prompt: `_prompt` remains part of the
    # schema `scripts/validate_figures_meta.py` enforces, even though nothing
    # consumes it in this deployment (no image-model credential).
    # Forest-mode items are LaTeX-only and data_chart items are drawn from the
    # corpus; neither has a prompt, and both are checked below on their own terms.
    missing_prompts = [
        it["figure_id"]
        for it in items
        if it.get("_render_mode") not in ("forest_taxonomy", "data_chart")
        and not (it.get("_prompt") or "").strip()
    ]
    if missing_prompts:
        write_status(ws, "generate_images", "FAILED",
                     duration_sec=round(time.time() - started, 2),
                     message=f"figures missing _prompt: {missing_prompts[:10]}")
        return 2

    rendered = 0
    forest_skipped = 0
    charts_rendered = 0
    charts_failed = 0
    images_rendered = 0
    images_failed = 0
    cjk_fallbacks: list[str] = []
    trim_notes: list[dict] = []
    watermark_results: list[dict] = []
    provider_used: set = set()
    failed: list[dict] = []
    image_items: list[dict] = []

    for it in items:
        fid = it["figure_id"]
        mode = it.get("_render_mode")
        if it.get('_generated') and (mode=='forest_taxonomy' or (ws.figures_dir/f'{fid}.png').is_file()):
            rendered += 1
            continue

        if mode == "forest_taxonomy":
            # LaTeX-native: rendered by the compiler, never by an image model.
            body_err = "" if (it.get("_latex_body") or "").strip() else \
                "forest_taxonomy mode but _latex_body empty"
            if not body_err:
                it["_generated"] = True
                forest_skipped += 1
                rendered += 1
                log_item(ws, "FIG-IMG", f"figure_id={fid}", 0.0,
                         status="SUCCESS", mode="forest_taxonomy")
            else:
                it["_generated"] = False
                failed.append({"figure_id": fid, "error": body_err})
                log_item(ws, "FIG-IMG", f"figure_id={fid}", 0.0,
                         status="FAILED", error=body_err)

        elif mode == "data_chart":
            t0 = time.time()
            ok, error, extra = _render_data_chart(ws, it)
            it.update(extra)
            if ok:
                it["_generated"] = True
                rendered += 1
                charts_rendered += 1
                cjk = (extra.get("_chart_meta") or {}).get("cjk") or {}
                if cjk.get("fallback_to_ascii_labels"):
                    cjk_fallbacks.append(fid)
                log_item(ws, "FIG-IMG", f"figure_id={fid}", time.time() - t0,
                         status="SUCCESS", mode="data_chart",
                         statistic=(extra.get("_chart_meta") or {}).get("statistic"))
            else:
                it["_generated"] = False
                charts_failed += 1
                failed.append({"figure_id": fid, "error": error})
                log_item(ws, "FIG-IMG", f"figure_id={fid}", time.time() - t0,
                         status="FAILED", mode="data_chart", error=error)

        else:
            # Image mode. Deferred to the concurrent pass below — each call is
            # 30-50 seconds of waiting on someone else's GPU, and the figures
            # are independent, so running them one at a time is pure
            # wall-clock. Charts and forests stay inline; they are local and
            # fast, and interleaving them would buy nothing.
            image_items.append(it)

    if image_items and not img_cfg:
        # No credential. Exactly the pre-integration behaviour: mark the
        # figures dropped so write_latex.py writes no `.tex` and
        # phase05b_insert_assets scrubs the dangling `\ref{fig:...}`.
        for it in image_items:
            it["_generated"] = False
            failed.append({"figure_id": it["figure_id"], "error": SKIP_REASON})
            log_item(ws, "FIG-IMG", f"figure_id={it['figure_id']}", 0.0,
                     status="SKIPPED", error=SKIP_REASON)
    elif image_items:
        workers = max(1, min(args.concurrency, len(image_items)))
        with ThreadPoolExecutor(max_workers=workers) as pool:
            futures = {pool.submit(_generate_image, ws, img_cfg, it): it
                       for it in image_items}
            for fut in as_completed(futures):
                it = futures[fut]
                fid = it["figure_id"]
                t0 = time.time()
                try:
                    ok, error, extra = fut.result()
                except Exception as e:  # noqa: BLE001
                    ok, error, extra = False, f"{type(e).__name__}: {e}", {}
                it.update(extra)
                meta = extra.get("_image_meta") or {}
                if ok:
                    it["_generated"] = True
                    rendered += 1
                    images_rendered += 1
                    if meta.get("stage"):
                        provider_used.add(meta["stage"])
                    watermark_results.append({"figure_id":fid, **(meta.get("watermark") or {})})
                    trim = (meta.get("trim") or {})
                    if trim.get("status") not in ("ok", "noop", None):
                        # Never fatal — the image is still a figure — but two
                        # things have to be visible from the status line or
                        # they are invisible until someone opens the PDF: a
                        # trimmer that could not run (margins come back), and
                        # a crop that revealed a mostly-empty canvas.
                        trim_notes.append({"figure_id": fid, **trim})
                    log_item(ws, "FIG-IMG", f"figure_id={fid}", time.time() - t0,
                             status="SUCCESS", mode="image",
                             size=meta.get("size"), trim=trim.get("status"))
                else:
                    it["_generated"] = False
                    images_failed += 1
                    failed.append({"figure_id": fid, "error": error})
                    log_item(ws, "FIG-IMG", f"figure_id={fid}", time.time() - t0,
                             status="FAILED", mode="image", error=error)

    write_json(worklist_path, worklist)

    # Any dropped figure degrades the run to PARTIAL_SUCCESS, but the exit code
    # stays 0 so the phase script continues to write_latex.py.
    final = "SUCCESS" if not failed else "PARTIAL_SUCCESS"
    write_status(ws, "generate_images", final,
                 duration_sec=round(time.time() - started, 2),
                 rendered=rendered, forest_skipped=forest_skipped,
                 charts_rendered=charts_rendered, charts_failed=charts_failed,
                 charts_with_cjk_fallback=cjk_fallbacks,
                 images_rendered=images_rendered, images_failed=images_failed,
                 # Trim outcomes worth a human's attention: a trimmer that
                 # could not run, or a crop that came out a sliver because the
                 # model returned an almost-empty canvas. Neither is fatal and
                 # neither is visible anywhere else.
                 image_trim_notes=trim_notes, image_watermarks=watermark_results,
                 failed=failed, total=len(items),
                 image_generation=("enabled" if img_cfg else "disabled"),
                 image_provider=({"stage": img_cfg.get("_stage"),
                                  "model": img_cfg.get("model"),
                                  "backend": img_cfg.get("backend")}
                                 if img_cfg else None),
                 image_provider_used=sorted(provider_used),
                 tcp_keepalive=True,
                 tcp_keepidle_sec=IMAGE_TCP_KEEPIDLE_SEC,
                 resume_only=args.resume_only)
    return 0


if __name__ == "__main__":
    sys.exit(main())
