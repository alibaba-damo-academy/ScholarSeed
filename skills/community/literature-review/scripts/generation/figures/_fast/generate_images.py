def _run(cmd: list[str], cwd: Path) -> tuple[int, str, str]:
    try:
        proc = subprocess.run([sys.executable, *cmd], cwd=str(cwd),
                              capture_output=True, text=True,
                              timeout=CHART_TIMEOUT_SEC)
        return proc.returncode, proc.stdout, proc.stderr
    except subprocess.TimeoutExpired:
        return 124, "", f"timed out after {CHART_TIMEOUT_SEC}s"


def _render_data_chart(ws: Workspace, item: dict) -> tuple[bool, str, dict]:
    """Compute + draw one data_chart. Returns (ok, error, extra_fields).

    `extra_fields` is merged onto the worklist item so the provenance of the
    numbers travels with the figure metadata rather than only on disk.
    """
    fid = item["figure_id"]
    spec = item.get("_chart_spec") or {}
    statistic = str(spec.get("statistic") or "").strip()
    chart_type = str(spec.get("chart_type") or "").strip()
    if not statistic or not chart_type:
        return False, "data_chart missing _chart_spec.statistic / .chart_type", {}

    data_dir = ws.figures_dir / "_data"
    csv_path = data_dir / f"{fid}.csv"
    sidecar_path = data_dir / f"{fid}.meta.json"
    png_path = ws.figures_dir / f"{fid}.png"
    pdf_path = ws.figures_dir / f"{fid}.pdf"
    render_meta_path = data_dir / f"{fid}.render.json"

    # ---- 1. Derive the numbers from the corpus. Never from the model. ----
    compute_cmd = [
        str(COMPUTE_SCRIPT),
        "--workspace", str(ws.root),
        "--statistic", statistic,
        "--out-dir", str(data_dir),
        "--basename", fid,
    ]
    top_n = str(spec.get("top_n") or "").strip()
    if top_n.isdigit():
        compute_cmd += ["--top-n", top_n]
    code, out, err = _run(compute_cmd, ws.root)
    if code != 0:
        detail = (err or out).strip().splitlines()[-1] if (err or out).strip() else ""
        kind = "no data for" if code == 2 else "could not compute"
        return False, f"{kind} statistic '{statistic}': {detail}", {}

    try:
        sidecar = json.loads(sidecar_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        sidecar = {}

    # ---- 2. Draw it. The renderer reads only the CSV. ----
    render_cmd = [
        str(RENDER_SCRIPT),
        "--csv", str(csv_path),
        "--out", str(png_path),
        "--vector", str(pdf_path),
        "--chart-type", chart_type,
        "--x-label", str(spec.get("x_label") or ""),
        "--y-label", str(spec.get("y_label") or ""),
        "--title", str(spec.get("title") or ""),
        "--x-label-fallback", str(spec.get("x_label_fallback") or ""),
        "--y-label-fallback", str(spec.get("y_label_fallback") or ""),
        "--title-fallback", str(spec.get("title_fallback") or ""),
        "--language", str(item.get("language") or "english"),
        "--meta-out", str(render_meta_path),
    ]
    code, out, err = _run(render_cmd, ws.root)
    if code != 0:
        detail = " | ".join(ln.strip() for ln in (err or out).strip().splitlines()[-4:])
        # Exit 2 is the renderer's QC gate: it wrote nothing, on purpose.
        kind = "chart failed QC (not written)" if code == 2 else "chart render failed"
        return False, f"{kind}: {detail}", {}

    try:
        render_meta = json.loads(render_meta_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        render_meta = {}

    extra = {
        "_chart_data": {
            "csv": str(csv_path),
            "sidecar": str(sidecar_path),
            "png": str(png_path),
            "vector": str(pdf_path),
        },
        "_chart_meta": {
            "statistic": statistic,
            "chart_type": chart_type,
            "rows": sidecar.get("rows"),
            "papers_in_corpus": sidecar.get("papers_in_corpus"),
            "source_files": sidecar.get("source_files"),
            "computed_at": sidecar.get("computed_at"),
            "cjk": render_meta.get("cjk"),
        },
    }
    return True, "", extra


