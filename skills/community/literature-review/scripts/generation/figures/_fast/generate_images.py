"""generate_images.py — realise every figure in the worklist.

Three kinds of figure, three mechanisms:

    forest_taxonomy — drawn natively in LaTeX from `_latex_body`. No model.
    data_chart      — numbers computed from the corpus, drawn by matplotlib.
                      No model, and deliberately so.
    image           — generated by an image model from `_prompt`.

Image generation is **conditional on a credential**, and runs against the
single `figures_image` stage (gpt-image-2 on IdeaLab). The stage prefers
`IMAGE_API_KEY` and falls back to `SCHOLARSEED_ACCOUNT_TOKEN`; `IMAGE_BASE_URL` overrides the
configured IdeaLab URL. With no credential, image-mode figures are marked
failed; manuscript assembly waits for those tasks to be corrected.

One property of the result is contract, not preference, and is therefore not
configurable per figure:

  * **PNG.** `write_latex.py` emits `\\includegraphics{figures/{fid}.png}` and
    `phase08_finalize` counts a figure as generated by testing for that exact
    file.

What the planner *does* choose is the size preset; see `SIZE_PRESETS`.

Reads:
    {workspace}/05_generation/_internal/figures_worklist.json

Writes:
    {workspace}/05_generation/_internal/figures_worklist.json
        with `_generated: true|false` for each item; `data_chart` items also
        gain `_chart_data` (paths to the CSV and its sidecar) and `_chart_meta`
        (what was drawn, including the CJK-font decision).
    {workspace}/05_generation/figures/{figure_id}.png   — data_chart raster
    {workspace}/05_generation/figures/{figure_id}.pdf   — data_chart vector
    {workspace}/05_generation/figures/_data/{figure_id}.csv       — the numbers
    {workspace}/05_generation/figures/_data/{figure_id}.meta.json — provenance
    {workspace}/05_generation/_status/generate_images.json
        `failed[]` lists every dropped figure_id — both
        merge/phase05b_insert_assets.py and the fast-audit verifier key off it.

Behaviour per `_render_mode`:
    "forest_taxonomy" — unaffected. Drawn natively in LaTeX from `_latex_body`,
                        so it needs no image model and is marked
                        `_generated: true`.
    "data_chart"      — the figure's numbers are derived from the corpus by
                        `compute_chart_data.py` and drawn by `render_chart.py`.
                        Neither script is an LLM and neither invents a value;
                        see their module docstrings for why that separation is
                        the point. Succeeds → `_generated: true` and a PNG on
                        disk, so write_latex.py emits an `\\includegraphics`
                        wrapper exactly as it would for a real image.
    "image" (default) — generated from `_prompt` at the `_image_size` preset,
                        cropped vertically, stamped with the publisher watermark, written as
                        `figures/{figure_id}.png`. Requests run concurrently
                        (`--concurrency`) because each is 30-50s of waiting and
                        the figures are independent. Already on disk and
                        `_generated: true` → not regenerated; an image costs
                        real money.
                        With no credential configured, or on failure after
                        retries, the figure is marked `_generated: false` and
                        recorded in `failed[]`. write_latex.py then writes no
                        `.tex` for it and phase05b_insert_assets scrubs the
                        now-dangling `\\ref{fig:...}` from the prose.

The chart pair runs as a SUBPROCESS rather than an import, because
`render_chart.py` signals QC failure through its exit code (2 = QC failed, no
file written) and that contract is only meaningful across a process boundary. A
chart that fails QC is treated exactly like a failed image: dropped, recorded in
`failed[]`, its `\\ref` scrubbed. A figure that fails QC must not ship.

Dropped figures yield PARTIAL_SUCCESS with exit code 0, so the phase script's
`&&` chain continues on to write_latex.py.
"""
