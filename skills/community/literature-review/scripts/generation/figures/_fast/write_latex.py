def _is_renderable(workspace: Workspace, item: dict) -> bool:
    """True when the figure has real content to render.

    A forest_taxonomy figure is renderable iff it carries a non-empty
    ``_latex_body``. A data_chart or an image figure is renderable iff
    ``_generated`` is truthy and the PNG exists on disk. For a data_chart that
    means compute+render both succeeded and the render passed QC; for an image
    it never happens while image generation is disabled. Everything else is
    dropped, not placeheld.

    The PNG-on-disk test is deliberately kept for data_chart rather than
    trusting ``_generated`` alone: render_chart.py deletes a stale output when
    its QC fails, so file presence is the honest signal.
    """
    if item.get("_render_mode") == "forest_taxonomy":
        return bool((item.get("_latex_body") or "").strip())
    fid = item.get("figure_id")
    return bool(item.get("_generated")) and (workspace.figures_dir / f"{fid}.png").exists()


def _emit(item: dict) -> str:
    """Render the `\\begin{figure}` wrapper. Only called for items that
    `_is_renderable()` accepted, so both branches always have real content."""
    fid = item["figure_id"]
    label = item["label"]
    from figure_caption import caption_latex
    # Only the authored publication caption is allowed; the outline skeleton
    # describes intent and is never a final-caption fallback.
    caption = caption_latex(item.get('_caption'))

    if item.get("_render_mode") == "forest_taxonomy":
        return (
            "\\begin{figure}[t]\n"
            "\\centering\n"
            "\\resizebox{\\linewidth}{!}{%\n"
            f"{(item.get('_latex_body') or '').strip()}%\n"
            "}\n"
            f"\\caption{{{caption}}}\n"
            f"\\label{{{label}}}\n"
            "\\end{figure}\n"
        )

    return (
        "\\begin{figure}[t]\n"
        "\\centering\n"
        f"\\includegraphics[width=\\linewidth]{{figures/{fid}.png}}\n"
        f"\\caption{{{caption}}}\n"
        f"\\label{{{label}}}\n"
        "\\end{figure}\n"
    )


def main() -> int:
    p = argparse.ArgumentParser()
    p.parse_args()

    started = time.time()
    ws = Workspace()
    log_script_start(ws, "write_latex")

    if not ws.figures_worklist_path().exists():
        write_status(ws, "write_latex", "FAILED",
                     duration_sec=round(time.time() - started, 2),
                     message="figures_worklist.json not found.")
        return 2
    worklist = load_json(ws.figures_worklist_path())
    items = worklist["items"]

    missing_caption = [it["figure_id"] for it in items if not (it.get("_caption") or "").strip()]
    if missing_caption:
        write_status(ws, "write_latex", "FAILED",
                     duration_sec=round(time.time() - started, 2),
                     message=f"figures missing _caption: {missing_caption[:10]}")
        return 2

    written = 0
    dropped = 0
    forest_figures = 0
    chart_figures = 0
    dropped_ids: list[str] = []
    for it in items:
        out = ws.figures_dir / f"{it['figure_id']}.tex"
        out.parent.mkdir(parents=True, exist_ok=True)
        if not _is_renderable(ws, it):
            # No usable render (failed image / empty forest body): drop the
            # figure rather than emit a placeholder. Remove any stale .tex from
            # a prior run so insert_assets (keyed off file presence) and the
            # Markdown fallback both skip it cleanly.
            if out.exists():
                try:
                    out.unlink()
                except OSError:
                    pass
            dropped += 1
            dropped_ids.append(it["figure_id"])
            continue
        tex = _emit(it)
        out.write_text(tex, encoding="utf-8")
        written += 1
        if it.get("_render_mode") == "forest_taxonomy" and (it.get("_latex_body") or "").strip():
            forest_figures += 1
        elif it.get("_render_mode") == "data_chart":
            chart_figures += 1

    write_status(ws, "write_latex", "SUCCESS",
                 duration_sec=round(time.time() - started, 2),
                 written=written, forest_figures=forest_figures,
                 chart_figures=chart_figures,
                 dropped=dropped, dropped_ids=dropped_ids, total=len(items))
    return 0


if __name__ == "__main__":
    sys.exit(main())
