"""write_latex.py — emit LaTeX `\\begin{figure}` wrappers for each figure.

Reads:
    {workspace}/05_generation/_internal/figures_worklist.json
        Every item must have a non-null, non-empty `_caption`.

Writes:
    {workspace}/05_generation/figures/{figure_id}.tex
        Branches on `_render_mode`:
        - "forest_taxonomy" with `_latex_body` set →
            `\\begin{figure} \\resizebox{\\linewidth}{!}{<body>} \\caption \\label`
        - "data_chart" with `_generated: true` AND PNG present →
            `\\includegraphics` (see the note on the raster below)
        - "image" (default) with `_generated: true` AND PNG present →
            `\\includegraphics`
        - figure with no usable render (image with no PNG, a data_chart whose
          render failed QC, or forest_taxonomy with an empty body) → NO .tex is
          written and any stale .tex from a prior run is removed. The figure is
          reported missing rather than rendered as a placeholder; native v1
          assembly waits for every required real figure.

    Image generation runs in figures plan-generate before v1 assembly. The
    manuscript coordinator waits for successful files, not seals or caches.
    Publication never invokes image generation or silently drops planned figures.

    Why the wrapper points at the PNG and not the vector PDF: render_chart.py
    emits both, but three downstream consumers this file does not own read the
    raster specifically — phase07's Markdown fallback embeds
    `image_filename` parsed out of `\\includegraphics`, and phase08 counts a
    figure as generated by testing for `{figure_id}.png`. The `.pdf` is copied
    into the output bundle alongside the PNG by phase07's `copytree`, so anyone
    recompiling at print resolution has it; pointing the wrapper at it would
    silently break the Markdown path.
"""
