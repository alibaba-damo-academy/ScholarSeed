"""Locate the first PDF page and current figures/tables, including longtable spans."""
from collections import defaultdict
from pathlib import Path
import re
from pypdf import PdfReader
from pypdf.errors import PyPdfError

from native_asset_checks import visible_source, latex_blocks, _braced
from publication_files import source_bundle

END_PREFIX = 'slr:longtable:end:'

# Loaded before the user's source at compile time, never inserted into editable v2.
# crcr also handles a last row without an explicit \\; the zero-size write node
# stays inside the final alignment chunk, so its page is the table's actual end.
TRACKING_TEX = r'''\AddToHook{begindocument/end}{%
  \ifdefined\endlongtable
    \let\slrOriginalEndlongtable\endlongtable
    \def\endlongtable{%
      \crcr\noalign{\label{slr:longtable:end:\thetable}}%
      \slrOriginalEndlongtable}%
  \fi
}
'''

def aux_labels(path):
    """Read newlabel records and included aux files without executing TeX."""
    records = defaultdict(list)
    pending, seen = [Path(path)], set()
    while pending:
        current = pending.pop().resolve()
        if current in seen or not current.is_file():
            continue
        seen.add(current)
        text = visible_source(current.read_text(encoding='utf-8', errors='replace'))
        for match in re.finditer(r'\\newlabel\s*\{([^{}]+)\}\s*(?=\{)', text):
            body = _braced(text, match.end())
            if body is None:
                continue
            fields = []
            pos = 0
            while pos < len(body):
                if body[pos].isspace():
                    pos += 1
                    continue
                value = _braced(body, pos)
                if value is None:
                    break
                fields.append(value)
                pos += len(value) + 2
            if len(fields) >= 2:
                pair = (fields[0], fields[1])
                if pair not in records[match[1]]:
                    records[match[1]].append(pair)
        for name in re.findall(r'\\@input\s*\{([^{}]+\.aux)\}', text):
            pending.append(current.parent / name)
    return records


def inspection_plan(source, pdf):
    """Use PDF page labels to translate TeX numbering into physical page numbers."""
    try:
        reader = PdfReader(pdf)
        page_labels = reader.page_labels
    except PyPdfError as exc:
        raise ValueError(str(exc)) from exc
    pages = {1: {'page_number': 1, 'page_label': page_labels[0],
                 'first_page': True, 'assets': []}} if page_labels else {}
    issues, assets = [], {}
    if not page_labels:
        issues.append({'code':'pdf_has_no_pages'})
    if source is None:
        issues.append({'code': 'source_unavailable',
                       'message': 'Cannot locate figure/table pages without the current publication source.'})
    else:
        source = Path(source)
        sources, _ = source_bundle(source)
        for target, raw in sources.items():
            if target != 'main' and not target.endswith('.tex'):
                continue
            text = visible_source(raw)
            for start, _, kind, block in latex_blocks(text):
                labels = list(dict.fromkeys(re.findall(r'\\label\s*\{((?:fig|tab)[:-][^{}]+)\}', block)))
                if not labels:
                    issues.append({'code': 'asset_label_missing', 'target': target,
                                   'source_line': text.count('\n', 0, start) + 1, 'kind': kind})
                for label in labels:
                    assets[label] = {'longtable': r'\begin{longtable}' in block}
            # Labels generated by wrappers outside a standard float still matter.
            for label in re.findall(r'\\label\s*\{((?:fig|tab)[:-][^{}]+)\}', text):
                assets.setdefault(label, {'longtable': False})
        records = aux_labels(source.with_suffix('.aux'))
        for label in records:
            if re.match(r'^(fig|tab)[:-]', label) and not label.endswith('@cref'):
                assets.setdefault(label, {'longtable': False})
        by_label = defaultdict(list)
        for index, label in enumerate(page_labels, 1):
            by_label[label].append(index)

        def locate(label, owner):
            values = records.get(label, [])
            if len(values) != 1:
                issues.append({'code': 'aux_label_missing_or_ambiguous', 'asset': owner, 'label': label})
                return None
            candidates = by_label.get(values[0][1], [])
            if len(candidates) != 1:
                issues.append({'code': 'pdf_page_label_missing_or_ambiguous', 'asset': owner,
                               'page_label': values[0][1]})
                return None
            return candidates[0]

        def include(page, label):
            row = pages.setdefault(page, {'page_number': page, 'page_label': page_labels[page-1],
                                          'first_page': page == 1, 'assets': []})
            if label not in row['assets']:
                row['assets'].append(label)

        for label, asset in assets.items():
            start = locate(label, label)
            if start is None:
                continue
            include(start, label)
            end_key = END_PREFIX + records[label][0][0]
            if asset['longtable'] or (label.startswith(('tab:','tab-')) and end_key in records):
                end = locate(end_key, label)
                if end is not None:
                    if end < start:
                        issues.append({'code': 'longtable_page_range_invalid', 'asset': label})
                    else:
                        for page in range(start, end + 1):
                            include(page, label)
    return {'status': 'PARTIAL_SUCCESS' if issues else 'SUCCESS', 'complete': not issues,
            'pages': [pages[p] for p in sorted(pages)], 'issues': issues}
