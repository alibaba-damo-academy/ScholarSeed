import assert from 'node:assert/strict'
import { test } from 'node:test'
import { PreviewFiles, PREVIEW_FILE_ERROR } from './files.ts'
import { PreviewBrowsing } from './browsing.ts'
import { PREVIEW_BROWSING } from './listing.ts'
import type { PreviewBrowsingPolicy } from './listing.ts'

test('sample tree and recursive listing derive directories and files from the original VFS', async () => {
  const files = new PreviewFiles()
  const before = files.manifest()
  const owner = new PreviewBrowsing(files, { seed: 'sample' })
  assert.deepEqual(files.manifest(), before)
  files.write('nested/deep/leaf.md', new TextEncoder().encode('nested'))
  const listing = await owner.listing()
  assert.equal(listing.length, before.length + 3)
  assert.deepEqual(listing.filter(entry => entry.kind === 'dir').map(entry => entry.path), ['nested', 'nested/deep'])
  assert.deepEqual(listing.find(entry => entry.path === 'nested/deep/leaf.md'), files.fileInfo('nested/deep/leaf.md'))
  const tree = await owner.tree()
  assert.equal(tree.entries[0].kind, 'dir')
  assert.equal(tree.total, before.length + 1)
  assert.deepEqual((await owner.tree('nested')).entries.map(entry => entry.path), ['nested/deep'])
  const original = files.read('readme.md')
  const item = tree.entries.find(entry => entry.path === original.path)!
  assert.equal(item.identity, original.identity)
  const changed = await owner.listing()
  changed.splice(0)
  assert.equal((await owner.listing()).length, listing.length)
  files.rename('readme.md', 'renamed.md')
  assert.ok((await owner.listing()).some(entry => entry.path === 'renamed.md' && entry.identity === original.identity))
  files.delete('nested')
  assert.ok(!(await owner.listing()).some(entry => entry.kind === 'dir'))
})

test('empty seed changes the same VFS while paged seed preserves samples and contains real readable files', async () => {
  const emptyFiles = new PreviewFiles()
  const empty = new PreviewBrowsing(emptyFiles, { seed: 'empty' })
  assert.deepEqual(emptyFiles.manifest(), [])
  assert.deepEqual(await empty.tree(), { entries: [], total: 0, offset: 0 })
  assert.deepEqual(await empty.listing(), [])
  const files = new PreviewFiles()
  const sample = files.read('sample.pdf')
  const owner = new PreviewBrowsing(files, { seed: 'paged' })
  assert.deepEqual(files.read('sample.pdf'), sample)
  const first = await owner.tree()
  const second = await owner.tree('', PREVIEW_BROWSING.pageSize)
  assert.equal(first.entries.length, PREVIEW_BROWSING.pageSize)
  assert.ok(second.entries.length > 0)
  const paths = [...first.entries, ...second.entries].map(entry => entry.path)
  assert.equal(new Set(paths).size, first.total)
  assert.deepEqual((await owner.tree('', first.total + 100)), { entries: [], total: first.total, offset: first.total })
  for (const entry of (await owner.listing()).filter(entry => entry.kind === 'file')) assert.equal(files.read(entry.path).identity, entry.identity)
  assert.equal(new TextDecoder().decode(files.read(PREVIEW_BROWSING.seed.nested[1].path).bytes), PREVIEW_BROWSING.seed.nested[1].text)
})

test('more failure is per canonical nonempty page and invalid or cancelled requests do not consume it', async () => {
  const owner = new PreviewBrowsing(new PreviewFiles(), { seed: 'paged', explorerMore: 'fail-once' })
  const first = await owner.tree()
  for (const offset of [-1, 0.5, NaN, Infinity]) await assert.rejects(owner.tree('', offset), { status: 422 })
  await assert.rejects(owner.tree('../', 100), { code: PREVIEW_FILE_ERROR.invalidPath })
  await assert.rejects(owner.tree('readme.md', 100), { code: PREVIEW_FILE_ERROR.notDirectory })
  const aborted = new AbortController()
  aborted.abort()
  await assert.rejects(owner.tree('', 100, aborted.signal), { status: 410 })
  assert.deepEqual((await owner.tree('', first.total)).entries, [])
  await assert.rejects(owner.tree('', 100), { status: 503, message: PREVIEW_BROWSING.moreFailure })
  assert.ok((await owner.tree('.', 100)).entries.length > 0)
  await assert.rejects(owner.tree('', 101), { status: 503 })
  assert.ok((await owner.tree('', 101)).entries.length > 0)
})

test('persistent read failures are independent, recover explicitly without modifying files or more policy', async () => {
  for (const source of ['listing', 'explorer'] as const) {
    const files = new PreviewFiles()
    const policy: PreviewBrowsingPolicy = { seed: 'paged', explorerMore: 'fail-once', [source === 'listing' ? 'listingRead' : 'explorerRead']: 'failed' }
    const owner = new PreviewBrowsing(files, policy)
    const before = files.manifest()
    const failing = () => source === 'listing' ? owner.listing() : owner.tree()
    for (let count = 0; count < 2; count++) await assert.rejects(failing(), { status: 503 })
    if (source === 'listing') await owner.tree()
    else await owner.listing()
    owner.recover()
    owner.recover()
    await failing()
    assert.deepEqual(files.manifest(), before)
    await assert.rejects(owner.tree('', 100), { message: PREVIEW_BROWSING.moreFailure })
    assert.ok((await owner.tree('', 100)).entries.length)
    const reset = new PreviewBrowsing(new PreviewFiles(), policy)
    await assert.rejects(source === 'listing' ? reset.listing() : reset.tree(), { status: 503 })
  }
  assert.throws(() => new PreviewBrowsing(new PreviewFiles()).recover(), { status: 409 })
})

test('delays use current VFS facts and cancellation or disposal fences all pending receipts', async context => {
  context.mock.timers.enable({ apis: ['setTimeout'] })
  const files = new PreviewFiles()
  const policy: PreviewBrowsingPolicy = { seed: 'paged', listingRead: 'delayed', explorerRead: 'normal', explorerMore: 'delayed' }
  const owner = new PreviewBrowsing(files, policy)
  policy.listingRead = 'normal'
  let settled = false
  const read = owner.listing().then(entries => { settled = true; return entries })
  await owner.tree()
  files.write('new.md', new TextEncoder().encode('new'))
  context.mock.timers.tick(PREVIEW_BROWSING.delayMs - 1)
  await Promise.resolve()
  assert.equal(settled, false)
  context.mock.timers.tick(1)
  assert.ok((await read).some(entry => entry.path === 'new.md'))
  const controller = new AbortController()
  const cancelled = assert.rejects(owner.tree('', 100, controller.signal), { status: 410 })
  context.mock.timers.tick(PREVIEW_BROWSING.delayMs)
  controller.abort()
  await cancelled
  const listing = assert.rejects(owner.listing(), { status: 410 })
  const more = assert.rejects(owner.tree('', 100), { status: 410 })
  owner.dispose()
  context.mock.timers.tick(PREVIEW_BROWSING.delayMs)
  await Promise.all([listing, more])
  assert.throws(() => owner.recover(), { status: 410 })
  await assert.rejects(owner.tree(), { status: 410 })
  await assert.rejects(owner.listing(), { status: 410 })
})

test('each directory and owner has its own more receipt and snapshots cannot mutate VFS metadata', async () => {
  const files = new PreviewFiles()
  const owner = new PreviewBrowsing(files, { seed: 'paged', explorerMore: 'fail-once' })
  for (let index = 0; index <= PREVIEW_BROWSING.pageSize; index++) files.write(`another/item-${index}.md`, new Uint8Array([index]))
  await assert.rejects(owner.tree('', 100), { message: PREVIEW_BROWSING.moreFailure })
  await assert.rejects(owner.tree('another', 100), { message: PREVIEW_BROWSING.moreFailure })
  const result = await owner.tree('another/', 100)
  assert.equal(result.entries.length, 1)
  const original = result.entries[0]
  Object.assign(original, { name: 'modified', identity: 'modified' })
  assert.notEqual((await owner.tree('another', 100)).entries[0].identity, original.identity)
  const otherFiles = new PreviewFiles()
  const other = new PreviewBrowsing(otherFiles, { seed: 'paged', explorerMore: 'fail-once' })
  await assert.rejects(other.tree('', 100), { message: PREVIEW_BROWSING.moreFailure })
  assert.ok((await owner.tree('', 100)).entries.length)
  const before = otherFiles.manifest()
  owner.dispose()
  assert.deepEqual(otherFiles.manifest(), before)
  assert.ok((await other.tree('', 100)).entries.length)
})

test('delayed initial tree fences disposal after timer completion and rejects changed paths', async context => {
  context.mock.timers.enable({ apis: ['setTimeout'] })
  const files = new PreviewFiles()
  files.write('temporary/child.md', new Uint8Array([1]))
  const owner = new PreviewBrowsing(files, { seed: 'sample', explorerRead: 'delayed' })
  const missing = assert.rejects(owner.tree('temporary'), { code: PREVIEW_FILE_ERROR.notFound })
  files.delete('temporary')
  context.mock.timers.tick(PREVIEW_BROWSING.delayMs)
  await missing
  const aborted = new AbortController()
  aborted.abort()
  await assert.rejects(owner.listing(aborted.signal), { status: 410 })
  const old = assert.rejects(owner.tree(), { status: 410 })
  context.mock.timers.tick(PREVIEW_BROWSING.delayMs)
  owner.dispose()
  await old
  const recovered = new PreviewBrowsing(new PreviewFiles(), { seed: 'sample', listingRead: 'failed', explorerRead: 'failed' })
  recovered.recover()
  await recovered.tree()
  await recovered.listing()
})

test('synchronous page shares the projection without consuming or bypassing async caller policies', async () => {
  const owner = new PreviewBrowsing(new PreviewFiles(), { seed: 'paged', explorerRead: 'failed', explorerMore: 'fail-once' })
  assert.equal(owner.page().entries.length, PREVIEW_BROWSING.pageSize)
  const more = owner.page('', PREVIEW_BROWSING.pageSize)
  assert.ok(more.entries.length)
  await assert.rejects(owner.tree(), { message: PREVIEW_BROWSING.explorerFailure })
  await assert.rejects(owner.tree('', PREVIEW_BROWSING.pageSize), { message: PREVIEW_BROWSING.moreFailure })
  assert.deepEqual(await owner.tree('', PREVIEW_BROWSING.pageSize), more)
  owner.dispose()
  assert.throws(() => owner.page(), { status: 410 })
})
