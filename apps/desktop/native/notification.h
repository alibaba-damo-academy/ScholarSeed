#ifndef SCHOLARSEED_NOTIFICATION_H
#define SCHOLARSEED_NOTIFICATION_H

#include <stdint.h>

#define NOTIFICATION_SETTING_UNKNOWN (-1)
#define NOTIFICATION_SETTING_ENABLED 0
#define NOTIFICATION_SETTING_MISSING_HRESULT ((int32_t)0x80070490u)

enum notification_permission {
  NOTIFICATION_PERMISSION_ENABLED,
  NOTIFICATION_PERMISSION_UNAVAILABLE,
  NOTIFICATION_PERMISSION_DISABLED,
  NOTIFICATION_PERMISSION_ERROR
};

static enum notification_permission notification_permission(int32_t result, int32_t setting) {
  if (result == NOTIFICATION_SETTING_MISSING_HRESULT) return NOTIFICATION_PERMISSION_UNAVAILABLE;
  if (result < 0) return NOTIFICATION_PERMISSION_ERROR;
  return setting == NOTIFICATION_SETTING_ENABLED
    ? NOTIFICATION_PERMISSION_ENABLED : NOTIFICATION_PERMISSION_DISABLED;
}

#endif
