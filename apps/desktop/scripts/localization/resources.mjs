import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

export const DESKTOP = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
export const RESOURCE_DIRECTORY = resolve(DESKTOP, 'src/localization/locales')
export const GENERATED_TYPES = resolve(DESKTOP, 'src/localization/types.d.ts')
export const GENERATED_RESOURCES = resolve(DESKTOP, 'src/localization/resources.ts')
const BASE_LANGUAGE = 'zh'
const PLURAL = /_(zero|one|two|few|many|other)$/
const INTERPOLATION = /{{\s*-?\s*([\w.]+)(?:\s*,[^}]*)?\s*}}/g

export function flatten(value, prefix = '', result = {}) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`Invalid message tree: ${prefix}`)
  for (const [key, child] of Object.entries(value)) {
    const path = prefix ? `${prefix}.${key}` : key
    if (typeof child === 'string') {
      if (!child.trim()) throw new Error(`Empty message: ${path}`)
      result[path] = child
    } else flatten(child, path, result)
  }
  return result
}
export const parameters = (value) => [...new Set([...value.matchAll(INTERPOLATION)].map((m) => m[1]))].sort()


export function richTags(value) {
  const tags = new Set()
  const stack = []
  for (const match of value.matchAll(/<([^>]+)>/g)) {
    if (!/^\/?(?:[A-Za-z][\w-]*|\d+)\s*\/?$/.test(match[1])) throw new Error('Rich messages may contain component tags, not HTML attributes')
    const closing = match[1].startsWith('/')
    const name = match[1].replace(/^\/|\s*\/$/g, '').trim()
    tags.add(name)
    if (closing) { if (stack.pop() !== name) throw new Error('Unbalanced rich message tags') }
    else if (!match[1].endsWith('/')) stack.push(name)
  }
  if (stack.length) throw new Error('Unbalanced rich message tags')
  return [...tags].sort().join()
}

export function validateResources(resources) {
  const errors = []
  const languages = Object.keys(resources)
  const base = resources[BASE_LANGUAGE]
  if (!base) return ['Missing base language zh']
  for (const language of languages) {
    if (Object.keys(resources[language]).sort().join() !== Object.keys(base).sort().join()) errors.push(`${language}: namespace mismatch`)
    for (const namespace of Object.keys(base)) {
      try {
        const source = flatten(base[namespace])
        const target = flatten(resources[language][namespace])
        const groups = (messages) => {
          const result = new Map()
          for (const [key, value] of Object.entries(messages)) {
            const root = key.replace(PLURAL, '')
            const entries = result.get(root) ?? []
            entries.push({ key, value, plural: key.match(PLURAL)?.[1] })
            result.set(root, entries)
          }
          return result
        }
        const sources = groups(source)
        const targets = groups(target)
        for (const key of new Set([...sources.keys(), ...targets.keys()])) {
          const original = sources.get(key)
          const translated = targets.get(key)
          if (!original || !translated) { errors.push(`${language}/${namespace}:${key}: missing message`); continue }
          const plural = original.some((entry) => entry.plural)
          if (plural !== translated.some((entry) => entry.plural)) errors.push(`${language}/${namespace}:${key}: plural mismatch`)
          if (plural) {
            for (const form of new Intl.PluralRules(language).resolvedOptions().pluralCategories) {
              if (!translated.some((entry) => entry.plural === form)) errors.push(`${language}/${namespace}:${key}: missing plural ${form}`)
            }
          }
          const expected = parameters(original[0].value).join()
          const tags = richTags(original[0].value)
          for (const entry of [...original, ...translated]) {
            if (richTags(entry.value) !== tags) errors.push(`${language}/${namespace}:${entry.key}: rich component mismatch`)
            if (parameters(entry.value).join() !== expected) errors.push(`${language}/${namespace}:${entry.key}: parameter mismatch`)
          }
        }
      } catch (error) { errors.push(`${language}/${namespace}: ${error.message}`) }
    }
  }
  return errors
}

export function loadResources(directory = RESOURCE_DIRECTORY) {
  return Object.fromEntries(readdirSync(directory, { withFileTypes: true }).filter((e) => e.isDirectory()).map((entry) => [
    entry.name,
    Object.fromEntries(readdirSync(resolve(directory, entry.name)).filter((f) => f.endsWith('.json')).sort().map((file) => [
      file.slice(0, -5), JSON.parse(readFileSync(resolve(directory, entry.name, file), 'utf8'))
    ]))
  ]))
}

export function generateTypes(resources) {
  const errors = validateResources(resources)
  if (errors.length) throw new Error(errors.join('\n'))
  return `// GENERATED by scripts/localization/resources.mjs; edit JSON messages, not this file.\nimport 'i18next'\n\ndeclare module 'i18next' {\n  interface CustomTypeOptions {\n    defaultNS: 'foundation'\n    strictKeyChecks: true\n    resources: ${JSON.stringify(resources[BASE_LANGUAGE], null, 4)}\n  }\n}\n`
}

/** The runtime import inventory is generated from the same JSON tree as types. */
export function generateRegistration(resources) {
  const imports = []
  const languages = []
  for (const language of Object.keys(resources).sort()) {
    const namespaces = []
    for (const namespace of Object.keys(resources[language]).sort()) {
      if (![language, namespace].every((part) => /^[A-Za-z][\w-]*$/.test(part))) throw new Error('Invalid language or namespace path')
      const binding = `messages${imports.length}`
      imports.push(`import ${binding} from './locales/${language}/${namespace}.json'`)
      namespaces.push(`${JSON.stringify(namespace)}: ${binding}`)
    }
    languages.push(`  ${JSON.stringify(language)}: { ${namespaces.join(', ')} }`)
  }
  return `// GENERATED by scripts/localization/resources.mjs; edit JSON messages, not this file.\n${imports.join('\n')}\n\nexport const resources = {\n${languages.join(',\n')}\n}\n`
}

export function validateCatalog(resources, source) {
  const file = ts.createSourceFile('catalog.ts', source, ts.ScriptTarget.Latest, true)
  let locales
  for (const statement of file.statements) {
    if (!ts.isVariableStatement(statement)) continue
    for (const declaration of statement.declarationList.declarations) {
      if (declaration.name.getText(file) !== 'LOCALES') continue
      locales = declaration.initializer
      while (locales && (ts.isAsExpression(locales) || ts.isSatisfiesExpression(locales) || ts.isParenthesizedExpression(locales))) locales = locales.expression
    }
  }
  if (!locales || !ts.isObjectLiteralExpression(locales) || locales.properties.some((property) => !ts.isPropertyAssignment(property) || ts.isComputedPropertyName(property.name))) return ['LOCALES must explicitly register each supported language']
  const registered = locales.properties.map((property) => property.name.text).sort()
  if (registered.join() !== Object.keys(resources).sort().join()) return ['Locale catalog and JSON resource languages differ']
  return []
}

export function checkResourceFiles({ write = false, desktop = DESKTOP } = {}) {
  const resources = loadResources(resolve(desktop, 'src/localization/locales'))
  const errors = validateCatalog(resources, readFileSync(resolve(desktop, 'src/localization/catalog.ts'), 'utf8'))
  if (errors.length) throw new Error(errors.join('\n'))
  const outputs = [[resolve(desktop, 'src/localization/types.d.ts'), generateTypes(resources)], [resolve(desktop, 'src/localization/resources.ts'), generateRegistration(resources)]]
  for (const [path, output] of outputs) {
    if (write) writeFileSync(path, output)
    else if (readFileSync(path, 'utf8') !== output) throw new Error(`Generated localization artifact drifted: ${path}; run i18n:generate`)
  }
  return resources
}
