/** Desktop 规范、派生库存与防漂移门禁的单一实现。 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, extname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'
import postcss from 'postcss'

import { UI_REGISTRY } from '../../src/renderer/src/components/ui/registry.ts'
import { scan as scanReuse } from './reuse.mjs'
import { cssDebtErrors } from './css.mjs'
import { layerTokenFindings, visualErrors } from './visual.mjs'

const SCRIPTS_DIR = dirname(fileURLToPath(import.meta.url))
export const DESKTOP_DIR = resolve(SCRIPTS_DIR, '../..')
export const DOCS_DIR = join(DESKTOP_DIR, 'docs')
export const POLICY_PATH = join(SCRIPTS_DIR, 'standards.policy.json')
export const STYLE_BASELINE_PATH = join(SCRIPTS_DIR, 'standards.baseline.json')
const REGISTRY_PATH = join(DOCS_DIR, 'registry.json')
const GENERATED_NOTICE = '<!-- GENERATED by scripts/ci/standards.mjs; DO NOT EDIT. -->'
const REQUIRED_SECTIONS = [
  '## Scope / Non-goals',
  '## Source of truth',
  '## Current / Required / Gap / Advisory',
  '## Ownership / Dependency',
  '## Enforced by',
  '## Update triggers',
  '## Stop condition'
]
const RAW_COLOR_PATTERN = /#[0-9a-fA-F]{3,8}\b|\b(?:rgb|hsl)a?\s*\(/g
const FIXED_TAILWIND_COLOR_PATTERN = /\b(?:bg|text|border|fill|stroke)-(?:black|white|red|orange|yellow|green|blue|purple|pink|gray|slate|zinc|neutral|stone)-\d{2,3}\b|\b(?:bg|text|border|fill|stroke)-\[(?:#|rgb|hsl)/g
const POSIX = '/'

export function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

function key(path) {
  return relative(DESKTOP_DIR, path).split(/[\\/]/).join(POSIX)
}

function walk(directory, extensions = null, out = []) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) walk(path, extensions, out)
    else if (!extensions || extensions.includes(extname(entry.name))) out.push(path)
  }
  return out
}

function occurrences(source, pattern) {
  pattern.lastIndex = 0
  return [...source.matchAll(pattern)].length
}

export function scanStyles(policy = readJson(POLICY_PATH)) {
  const root = join(DESKTOP_DIR, policy.sourceRoot)
  const counts = {}
  const hits = []
  for (const path of walk(root, policy.sourceExtensions).sort()) {
    const normalized = `/${key(path)}`
    if (policy.styleExcludes.some((fragment) => normalized.includes(fragment))) continue
    const fileCounts = classifyStyleSource(readFileSync(path, 'utf8'), path, policy)
    const total = Object.values(fileCounts).reduce((sum, value) => sum + value, 0)
    if (total > 0) {
      counts[key(path)] = fileCounts
      hits.push({ path: key(path), ...fileCounts })
    }
  }
  return { counts, hits }
}

function literalText(node) {
  if (ts.isStringLiteralLike(node)) return node.text
  if (ts.isTemplateExpression(node)) return [node.head.text, ...node.templateSpans.map((span) => span.literal.text)].join('')
  return null
}

function unwrapExpression(node) {
  let current = node
  while (current && (ts.isAsExpression(current) || ts.isParenthesizedExpression(current) || ts.isSatisfiesExpression(current))) current = current.expression
  return current
}

export function classifyStyleSource(source, filename, policy = readJson(POLICY_PATH)) {
  const counts = { rawColor: 0, fixedTailwindColor: 0, visualInlineStyle: 0 }
  if (filename.endsWith('.css')) {
    postcss.parse(source, { from: filename }).walkDecls((declaration) => {
      counts.rawColor += occurrences(declaration.value, RAW_COLOR_PATTERN)
      counts.fixedTailwindColor += occurrences(declaration.value, FIXED_TAILWIND_COLOR_PATTERN)
    })
    return counts
  }
  const scriptKind = filename.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS
  const sourceFile = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true, scriptKind)
  function visit(node) {
    const text = literalText(node)
    if (text !== null) {
      counts.rawColor += occurrences(text, RAW_COLOR_PATTERN)
      counts.fixedTailwindColor += occurrences(text, FIXED_TAILWIND_COLOR_PATTERN)
    }
    if (ts.isJsxAttribute(node) && node.name.getText(sourceFile) === 'style' && node.initializer && ts.isJsxExpression(node.initializer)) {
      const expression = unwrapExpression(node.initializer.expression)
      if (expression && ts.isObjectLiteralExpression(expression)) {
        const properties = expression.properties.map((property) => property.name?.getText(sourceFile).replace(/^['"]|['"]$/g, ''))
        if (properties.some((property) => policy.visualInlineProperties.includes(property))) counts.visualInlineStyle += 1
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(sourceFile)
  return counts
}

export function moduleSpecifiers(source, filename = 'source.tsx') {
  const scriptKind = filename.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS
  const sourceFile = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true, scriptKind)
  const specifiers = []
  function visit(node) {
    if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier && ts.isStringLiteral(node.moduleSpecifier)) {
      specifiers.push(node.moduleSpecifier.text)
    } else if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword && node.arguments.length === 1 && ts.isStringLiteral(node.arguments[0])) {
      specifiers.push(node.arguments[0].text)
    }
    ts.forEachChild(node, visit)
  }
  visit(sourceFile)
  return specifiers
}

export function scanArchitecture() {
  const root = join(DESKTOP_DIR, 'src/renderer/src')
  const deepImports = []
  const reverseDependencies = []
  for (const path of walk(root, ['.ts', '.tsx']).sort()) {
    const pathKey = key(path)
    const source = readFileSync(path, 'utf8')
    for (const specifier of moduleSpecifiers(source, path)) {
      const isTestSurface = /(?:\.test\.|\.fixture\.)/.test(pathKey) || pathKey.includes('/components/examples/')
      if (!isTestSurface && !pathKey.includes('/components/ui/') && /components\/ui\//.test(specifier)) {
        deepImports.push({ path: pathKey, specifier })
      }
      if (pathKey.includes('/components/ui/')) {
        const resolved = resolve(dirname(path), specifier)
        const normalized = `/${key(resolved)}`
        const policy = readJson(POLICY_PATH)
        if (policy.uiForbiddenDependencies.some((fragment) => normalized.includes(fragment))) {
          reverseDependencies.push({ path: pathKey, specifier })
        }
      }
    }
  }
  return { deepImports, reverseDependencies }
}

/** Unlike page debt, shared UI must never retain a numeric z-index allowance. */
export function checkUiLayerTokens() {
  const root = join(DESKTOP_DIR, 'src/renderer/src/components/ui')
  const errors = []
  for (const path of walk(root, ['.ts', '.tsx', '.css']).sort()) {
    if (/\.(?:test|fixture)\./.test(path)) continue
    for (const hit of layerTokenFindings(readFileSync(path, 'utf8'), path)) {
      errors.push(`${key(path)}:${hit.line}: shared UI z-index must use a --vds-z-* token (${hit.value})`)
    }
  }
  return errors
}

function generateComponents() {
  const sourceRoot = '../../src/renderer/src/components'
  const rows = Object.entries(UI_REGISTRY).sort(([a], [b]) => a.localeCompare(b)).map(([family, entry]) =>
    `| ${family} | ${entry.exports.map((name) => `\`${name}\``).join(', ')} | ${entry.intents.slice(0, 4).join('、')} | ${entry.use.replaceAll('|', '\\|')} | ${entry.avoid.replaceAll('|', '\\|')} |`
  )
  const sections = ['business', 'primitive'].map((owner) => {
    const files = walk(join(DESKTOP_DIR, 'src/renderer/src/components', owner), ['.tsx', '.ts'])
      .filter((path) => !/\/(?:download)\/|\.(?:test|fixture)\./.test(path)).sort()
    const program = ts.createProgram(files, { noResolve: true, jsx: ts.JsxEmit.Preserve })
    const checker = program.getTypeChecker()
    const modules = files.flatMap((path) => {
      const sourceFile = program.getSourceFile(path)
      const symbol = sourceFile && checker.getSymbolAtLocation(sourceFile)
      if (!symbol) return []
      const names = checker.getExportsOfModule(symbol).map((item) => item.name).sort()
      if (!names.length) return []
      const file = relative(join(DESKTOP_DIR, 'src/renderer/src/components'), path).split(/[\\/]/).join('/')
      const imports = moduleSpecifiers(sourceFile.text, path)
      return [`| [${file}](${sourceRoot}/${file}) | ${names.map((name) => `\`${name}\``).join(', ')} | ${[...new Set(imports)].map((name) => `\`${name}\``).join(', ')} |`]
    })
    return `## ${owner} 模块资产\n\n共 ${modules.length} 个有导出的模块。导出包含组件、Provider、hook、类型和工具，不能把每个导出都当作 JSX 组件。直接依赖来自 import/re-export/dynamic import；使用前从源码检查必填 props、上下文及 API。\n\n| 源码 / 模块 | 导出名称（含类型） | 直接依赖入口 |\n| --- | --- | --- |\n${modules.join('\n')}`
  })
  return `${GENERATED_NOTICE}\n# 组件资产列表\n\n面向首次开发 Desktop 页面的同学，先读[复用指南](../design/assets.md)。\n\n## UI 组件族\n\n共 ${Object.keys(UI_REGISTRY).length} 个组件族。来源：[意图注册表](${sourceRoot}/ui/registry.ts)；导入与实现映射见 [UI 统一出口](${sourceRoot}/ui/index.ts)，运行示例见 [ComponentsPage](${sourceRoot}/examples/ComponentsPage.tsx)。通过出口跳到实现核对真实 props。\n\n| 组件族 | 可导入名称 | 搜索意图 | 适用场景 | 使用限制 / 避免误用 |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}\n\n${sections.join('\n\n')}\n`
}

function generateTokens() {
  const designDir = join(DESKTOP_DIR, 'src/renderer/src/design')
  const definitionFiles = [...walk(designDir, ['.css']), join(DESKTOP_DIR, 'src/renderer/src/styles.css')].filter(existsSync).sort()
  const definitions = new Map()
  for (const path of definitionFiles) {
    postcss.parse(readFileSync(path, 'utf8'), { from: path }).walkDecls(/^--/, (declaration) => {
      const items = definitions.get(declaration.prop) ?? []
      const selector = declaration.parent?.selector ?? `@${declaration.parent?.name ?? 'root'}`
      items.push({ path: key(path), selector, value: declaration.value.trim() })
      definitions.set(declaration.prop, items)
    })
  }
  const rows = [...definitions.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, items]) =>
    `| \`${name}\` | ${items.map((item) => `\`${item.path}\` · \`${item.selector}\``).join('<br>')} | ${items.length > 1 ? `variants (${items.length})` : 'single'} |`
  )
  return `${GENERATED_NOTICE}\n# Token 库存\n\n来源：\`src/renderer/src/design/*.css\` 与兼容入口 \`src/renderer/src/styles.css\`。同名变量可在主题 selector 下有多个 variant；跨兼容入口重复仍是审查信号。\n\n| Token | Definition contexts | Definitions |\n| --- | --- | --- |\n${rows.join('\n')}\n`
}

function totalStyle(counts) {
  return Object.values(counts).reduce((sum, item) => sum + Object.values(item).reduce((inner, value) => inner + value, 0), 0)
}

function generateDebt() {
  const native = scanReuse()
  const styles = scanStyles()
  const architecture = scanArchitecture()
  const nativeRows = Object.entries(native.counts).sort(([a], [b]) => a.localeCompare(b)).map(([path, count]) => `| \`${path}\` | ${count} |`)
  const styleRows = Object.entries(styles.counts).sort(([a], [b]) => a.localeCompare(b)).map(([path, count]) => `| \`${path}\` | ${count.rawColor} | ${count.fixedTailwindColor} | ${count.visualInlineStyle} |`)
  return `${GENERATED_NOTICE}\n# Desktop 债务库存\n\n来源：\`reuse.mjs\`、\`standards.mjs\` 的源码扫描。基线是迁移额度，不是许可。\n\n## Native controls\n\n总计：${native.hits.length}。\n\n| File | Count |\n| --- | ---: |\n${nativeRows.join('\n')}\n\n## Style debt\n\n总计：${totalStyle(styles.counts)}。\n\n| File | Raw color | Fixed Tailwind color | Visual inline style |\n| --- | ---: | ---: | ---: |\n${styleRows.join('\n')}\n\n## Architecture debt\n\n- UI deep imports: ${architecture.deepImports.length}\n- UI reverse dependencies: ${architecture.reverseDependencies.length}\n`
}

export function generatedDocuments() {
  return new Map([
    ['_generated/components.md', generateComponents()],
    ['_generated/tokens.md', generateTokens()],
    ['_generated/debt.md', generateDebt()]
  ])
}

function validateLinks(path, source, errors) {
  const pattern = /\[[^\]]+\]\(([^)]+)\)/g
  for (const match of source.matchAll(pattern)) {
    const target = match[1].split('#')[0]
    if (!target || /^(?:https?:|mailto:)/.test(target)) continue
    if (!existsSync(resolve(dirname(path), target))) errors.push(`${key(path)}: broken link ${target}`)
  }
}

export function compareRatchet(current, baseline, errors = []) {
  const categories = ['rawColor', 'fixedTailwindColor', 'visualInlineStyle']
  for (const path of new Set([...Object.keys(current), ...Object.keys(baseline)])) {
    for (const category of categories) {
      const actual = current[path]?.[category] ?? 0
      const allowed = baseline[path]?.[category] ?? 0
      if (actual > allowed) errors.push(`style debt increased: ${path} ${category} ${actual} > ${allowed}`)
      if (actual < allowed) errors.push(`style debt decreased: review the diff, then run standards.mjs --write-style-baseline to tighten it (${path} ${category} ${actual} < ${allowed})`)
    }
  }
  return errors
}

/** Symbol closure only: local custom properties count; scope and units need browser checks. */
export function unresolvedTokens(sources) {
  const definitions = new Set()
  const references = []
  for (const [path, source] of sources) {
    for (const match of source.matchAll(/(--vds-[\w-]+)["']?\s*:/g)) definitions.add(match[1])
    for (const match of source.matchAll(/var\((--vds-[\w-]+)\s*\)/g)) references.push({ path, token: match[1] })
  }
  return references.filter(({ token }) => !definitions.has(token))
}

export function checkTokenReferences() {
  const root = join(DESKTOP_DIR, 'src/renderer/src')
  const paths = [...walk(join(root, 'design'), ['.css']), ...walk(join(root, 'components/ui'), ['.ts', '.tsx'])]
  return unresolvedTokens(paths.map((path) => [key(path), readFileSync(path, 'utf8')]))
}

export function foundationCssErrors(source, path) {
  const errors = []
  const css = postcss.parse(source, { from: path })
  css.walkAtRules('apply', () => errors.push(`${path}: @apply bypasses Tailwind ownership`))
  css.walkRules((rule) => {
    let parent = rule.parent
    while (parent && !(parent.type === 'atrule' && /keyframes$/.test(parent.name))) parent = parent.parent
    if (parent) return
    const rootOnly = rule.selectors.every((selector) => /^:root(?:\[data-theme=(?:'|")(?:light|dark)(?:'|")\]|:not\(\[data-theme\]\)(?::not\(\.light\))?)?$/.test(selector.trim()))
    if (!rootOnly) errors.push(`${path}: owned selector must use Tailwind: ${rule.selector}`)
    rule.walkDecls((declaration) => {
      if (!declaration.prop.startsWith('--') && declaration.prop !== 'color-scheme') errors.push(`${path}: non-foundation declaration ${declaration.prop}`)
    })
  })
  return errors
}

function checkFoundationCss() {
  const root = join(DESKTOP_DIR, 'src/renderer/src')
  return [
    ...walk(join(root, 'design'), ['.css']).flatMap((path) => foundationCssErrors(readFileSync(path, 'utf8'), key(path))),
    ...walk(join(root, 'components/ui'), ['.css']).map((path) => `${key(path)}: UI styles must use Tailwind`)
  ]
}

export function checkStandards() {
  const errors = []
  try { errors.push(...visualErrors()) }
  catch (error) { errors.push(`visual gate failed: ${error.message}; ensure the audited Git base in scripts/ci/visual.mjs is available (fetch full history in shallow clones)`) }
  errors.push(...checkUiLayerTokens())
  errors.push(...checkFoundationCss())
  const renderer = join(DESKTOP_DIR, 'src/renderer/src')
  const cssSources = walk(renderer, ['.css']).filter((path) => !key(path).startsWith('src/renderer/src/design/'))
    .map((path) => [key(path), readFileSync(path, 'utf8')])
  const cssBaseline = readJson(join(SCRIPTS_DIR, 'css.baseline.json'))
  errors.push(...cssDebtErrors(cssSources, cssBaseline.files, readJson(join(SCRIPTS_DIR, 'css.exceptions.json')).overrides))
  for (const hit of checkTokenReferences()) errors.push(`undefined UI/design token: ${hit.path} ${hit.token}`)
  const registry = readJson(REGISTRY_PATH)
  for (const document of registry.documents) {
    const path = join(DOCS_DIR, document.path)
    if (!existsSync(path)) { errors.push(`missing document: ${document.path}`); continue }
    const source = readFileSync(path, 'utf8')
    for (const section of REQUIRED_SECTIONS) if (!source.includes(section)) errors.push(`${document.path}: missing ${section}`)
    if (!/^## (?:Examples and anti-patterns|正反例)[ 	]*$/m.test(source)) errors.push(`${document.path}: missing examples and anti-patterns section`)
    for (const status of ['current', 'required', 'gap', 'advisory']) if (!source.includes(`**${status}**`)) errors.push(`${document.path}: missing status ${status}`)
    for (const sourcePath of document.sources) if (!existsSync(join(DESKTOP_DIR, sourcePath))) errors.push(`${document.path}: missing source ${sourcePath}`)
    validateLinks(path, source, errors)
  }
  validateLinks(join(DOCS_DIR, 'README.md'), readFileSync(join(DOCS_DIR, 'README.md'), 'utf8'), errors)
  for (const [path, expected] of generatedDocuments()) {
    const absolute = join(DOCS_DIR, path)
    if (!existsSync(absolute) || readFileSync(absolute, 'utf8') !== expected) errors.push(`${path}: stale; run npm run docs:write`)
  }
  const architecture = scanArchitecture()
  for (const hit of architecture.deepImports) errors.push(`UI deep import: ${hit.path} -> ${hit.specifier}`)
  for (const hit of architecture.reverseDependencies) errors.push(`UI reverse dependency: ${hit.path} -> ${hit.specifier}`)
  compareRatchet(scanStyles().counts, readJson(STYLE_BASELINE_PATH), errors)
  return errors
}

export function writeGenerated() {
  for (const [path, source] of generatedDocuments()) writeFileSync(join(DOCS_DIR, path), source)
}

export function writeStyleBaseline() {
  writeFileSync(STYLE_BASELINE_PATH, `${JSON.stringify({ $comment: '由 standards.mjs 生成的样式债务棘轮；不得手改或用重写掩盖新增债务。', ...scanStyles().counts }, null, 2)}\n`)
}

if (process.argv.includes('--write')) writeGenerated()
else if (process.argv.includes('--write-style-baseline')) writeStyleBaseline()
else if (process.argv.includes('--check')) {
  const errors = checkStandards()
  if (errors.length) { console.error(errors.join('\n')); process.exitCode = 1 }
  else console.log('Desktop standards check passed.')
} else if (process.argv.includes('--report')) {
  console.log(JSON.stringify({ architecture: scanArchitecture(), styles: scanStyles() }, null, 2))
}
