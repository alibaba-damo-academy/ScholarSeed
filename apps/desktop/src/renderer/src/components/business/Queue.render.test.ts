import path from 'node:path'
import test from 'node:test'
import { chromium, expect } from '@playwright/test'
import { renderFixture } from '../../../../test-helpers/render.ts'

test('shared queue view requires callbacks and preserves state and admission gates', async (context) => {
  const fixture = await renderFixture(path.resolve(import.meta.dirname, '../..'), {
    launch: () => chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL }),
  })
  context.after(() => fixture.close())
  const page = await fixture.page(context)
  const open = (query = '') =>
    page.goto(`${fixture.url}components/business/Queue.render.fixture.html?${query}`)
  await open()
  await expect(page.getByTestId('queued-delete-fixture-queue')).toBeDisabled()
  await expect(page.getByTestId('queued-steer-fixture-queue')).toBeDisabled()
  await page.getByTestId('queued-more-fixture-queue').click()
  await expect(page.getByRole('menuitem')).toBeDisabled()
  await open('callbacks=yes')
  const queue = page.getByTestId('composer-message-queue')
  await expect(queue.getByRole('button', { name: /排队消息/ })).toHaveCount(0)
  await expect(queue.getByText('排队中', { exact: true })).toHaveCount(0)
  const remove = page.getByTestId('queued-delete-fixture-queue')
  const steer = page.getByTestId('queued-steer-fixture-queue')
  const more = page.getByTestId('queued-more-fixture-queue')
  await expect(remove).toHaveAccessibleName('删除')
  await expect(remove).toHaveAttribute('title', '删除')
  await expect(remove).toHaveText('')
  await expect(remove.locator('svg')).toHaveCount(1)
  await expect(steer.locator('svg')).toHaveCount(1)
  for (const button of [remove, steer, more]) {
    await expect(button).toHaveCSS('height', '24px')
    await expect(button.locator('svg')).toHaveCSS('width', '12px')
  }
  await expect(queue).toHaveCSS('padding-top', '0px')
  await expect(queue).toHaveCSS('border-bottom-width', '0px')
  await expect(queue).toHaveCSS('margin-bottom', '0px')
  await expect(page.getByTestId('queued-message-fixture-queue')).toHaveCSS('min-height', '40px')
  await expect(remove).toHaveClass(/vds-button--ghostIcon/)
  const summary = page.getByTestId('queued-summary-fixture-queue')
  const references = '[report.pdf]、[2 条注释]、[2 条划词] [论文检索][前序任务]'
  const fullSummary = `Fixture queued message ${references}`
  await expect(summary).toHaveText(fullSummary)
  await expect(summary).toHaveCSS('white-space', 'nowrap')
  await expect(summary).toHaveCSS('text-overflow', 'ellipsis')
  await summary.hover()
  await expect(page.getByRole('tooltip')).toHaveText(fullSummary)
  await summary.click()
  for (const text of [summary, steer]) {
    await expect(text).toHaveCSS('font-size', '12px')
    await expect(text).toHaveCSS('font-weight', '400')
  }
  await expect(queue.getByText('消息正文', { exact: true })).toHaveCount(0)
  await page.getByTestId('queued-more-fixture-queue').click()
  await expect(page.getByRole('menuitem')).toHaveCount(1)
  await page.getByRole('menuitem').click()
  await page.getByTestId('queued-steer-fixture-queue').click()
  await page.getByTestId('queued-delete-fixture-queue').click()
  await expect(page.getByTestId('queue-events')).toHaveText(
    'edit:fixture-queue|steer:fixture-queue|withdraw:fixture-queue'
  )
  await open('callbacks=yes&followUp')
  await page.getByTestId('queued-more-fixture-queue').click()
  await page.getByRole('menuitem', { name: '关闭排队' }).click()
  await expect(page.getByTestId('queued-message-fixture-queue')).toBeVisible()
  await page.getByTestId('queued-more-fixture-queue').click()
  await page.getByRole('menuitem', { name: '开启排队' }).click()
  await expect(page.getByTestId('queue-events')).toHaveText('mode:steer|mode:queue')
  await open('callbacks=yes&followUp&savingPreference')
  await page.getByTestId('queued-more-fixture-queue').click()
  await expect(page.getByRole('menuitem', { name: '关闭排队' })).toBeDisabled()
  await open('callbacks=yes&state=submitting')
  await expect(queue.getByText('排队中', { exact: true })).toHaveCount(0)
  await expect(page.getByTestId('queued-delete-fixture-queue')).toBeDisabled()
  await expect(page.getByTestId('queued-steer-fixture-queue')).toBeDisabled()
  await page.getByTestId('queued-more-fixture-queue').click()
  await expect(page.getByRole('menuitem')).toBeDisabled()
  await open('callbacks=yes&waiting')
  await expect(page.getByTestId('queued-steer-fixture-queue')).toBeDisabled()
  await open('callbacks=yes&state=waiting_resources')
  await expect(queue.getByText('排队中', { exact: true })).toHaveCount(0)
  await open('callbacks=yes&state=failed&creditBlocked')
  await expect(queue.getByText('回答生成失败', { exact: true })).toBeVisible()
  await expect(page.getByTestId('queued-send-fixture-queue')).toBeDisabled()
  await open('callbacks=yes&state=outcome_unknown&busy')
  await expect(page.getByTestId('queued-confirm-fixture-queue')).toBeDisabled()
  await expect(page.getByTestId('queued-send-fixture-queue')).toBeDisabled()
  await open('state=outcome_unknown')
  await expect(page.getByTestId('queued-confirm-fixture-queue')).toBeDisabled()
  await expect(page.getByTestId('queued-send-fixture-queue')).toBeDisabled()
  await open('callbacks=yes&state=outcome_unknown')
  await expect(page.getByTestId('queued-delete-fixture-queue')).toHaveCount(0)
  await page.getByTestId('queued-send-fixture-queue').click()
  await page.getByTestId('queued-confirm-fixture-queue').click()
  await expect(page.getByTestId('queue-events')).toHaveText(
    'check:fixture-queue|confirm:fixture-queue'
  )
  await open('callbacks=yes&state=failed&openUnknown&creditBlocked&noRecovery')
  const check = page.getByTestId('queued-send-fixture-queue')
  await expect(check).toHaveText('检查发送结果')
  await expect(check).toBeEnabled()
  await expect(page.getByText(/无法确认会话是否已创建/)).toBeVisible()
  await expect(page.getByTestId('queued-confirm-fixture-queue')).toHaveCount(0)
  await check.click()
  await check.click()
  await expect(page.getByTestId('queue-events')).toHaveText(
    'check:fixture-queue|check:fixture-queue'
  )
  await open('state=failed&openUnknown&noRecovery')
  await expect(check).toBeDisabled()
  await open('callbacks=yes&state=outcome_unknown&openUnknown')
  await expect(check).toBeEnabled()
  await expect(page.getByTestId('queued-confirm-fixture-queue')).toHaveCount(0)
  await expect(page.getByText(/无法确认会话是否已创建/)).toBeVisible()
  await check.click()
  await expect(page.getByTestId('queue-events')).toHaveText('check:fixture-queue')
  await page.setViewportSize({ width: 320, height: 640 })
  await open('attachmentOnly')
  await expect(summary).toHaveText(references)
  await expect
    .poll(() => summary.evaluate((text) => text.scrollWidth > text.clientWidth))
    .toBe(true)
  await expect(queue.getByText('引用消息', { exact: true })).toHaveCount(0)
  await summary.focus()
  await expect(page.getByRole('tooltip')).toHaveText(references)
})
