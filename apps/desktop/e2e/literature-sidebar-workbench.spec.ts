import { test, expect, type Locator } from '@playwright/test'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { DesktopSession, apiBase } from './fixtures/electron'
import { createRuntime } from './fixtures/runtime'

test('tag search keeps sidebar geometry stable when opened and dismissed', async ({}, testInfo) => {
  const runtime = createRuntime(testInfo)
  writeFileSync(join(runtime.userData, 'renderer-preferences.json'), JSON.stringify({ language: 'zh', onboarding: { seen: { home: true, project: true, globalLib: true, pdf: true } } }))
  const desktop = new DesktopSession(runtime, testInfo)
  try {
    const page = await desktop.launch()
    const sidebar = page.getByTestId('literature-panel')
    const header = sidebar.locator('.lit-section-head').filter({ hasText: '标签' })
    const tags = sidebar.locator('.lit-tags')
    const search = sidebar.getByRole('button', { name: '搜索标签', exact: true })
    const input = sidebar.getByRole('searchbox', { name: '搜索标签', exact: true })
    await expect(search).toBeVisible()
    const headerBefore = await header.boundingBox()
    const tagsBefore = await tags.boundingBox()
    expect(headerBefore).not.toBeNull()
    expect(tagsBefore).not.toBeNull()
    for (const dismiss of ['escape', 'blur'] as const) {
      await search.click()
      await expect(input).toBeFocused()
      await expect.poll(() => header.boundingBox()).toEqual(headerBefore)
      await expect.poll(() => tags.boundingBox()).toEqual(tagsBefore)
      if (dismiss === 'escape') {
        await input.press('Escape')
      } else {
        await input.press('Tab')
      }
      await expect(search).toBeVisible()
      await expect.poll(() => header.boundingBox()).toEqual(headerBefore)
      await expect.poll(() => tags.boundingBox()).toEqual(tagsBefore)
    }
  } finally {
    await desktop.attachArtifacts()
  }
})

test('literature sidebar: scope, hierarchy, geometry and persistent folds', async ({}, testInfo) => {
  const runtime = createRuntime(testInfo)
  writeFileSync(join(runtime.userData, 'renderer-preferences.json'), JSON.stringify({ language: 'zh', onboarding: { seen: { home: true, project: true, globalLib: true, pdf: true } } }))
  const desktop = new DesktopSession(runtime, testInfo)
  const evidence = resolve('../../tmp/test_snapshot/desktop/literature-sidebar')
  mkdirSync(evidence, { recursive: true })
  try {
    const page = await desktop.launch()
    page.setDefaultTimeout(12000)
    const base = await apiBase(page)
    await page.getByTestId('activity-literature').click()
    const sidebar = page.getByTestId('literature-panel')
    await expect(sidebar.getByText('我的文献', { exact: true })).toBeVisible()
    await expect(sidebar.locator('[data-sidebar-view]')).toHaveCount(3)
    await expect(sidebar).not.toContainText('项目')
    await page.screenshot({ path: join(evidence, 'no-projects.png') })
    const projectResponse = await page.request.post(`${base}/api/content/projects`, { data: { name: '测试091803' } })
    expect(projectResponse.ok()).toBe(true)
    const project = await projectResponse.json()
    const create = async (name: string, projectId = '', parentId = '') => {
      const response = await page.request.post(`${base}/api/v1/collections`, { data: { name, project_id: projectId, parent_id: parentId } })
      expect(response.ok(), await response.text()).toBe(true)
      return response.json()
    }
    const global = await create('会后')
    const globalChild = await create('9 月组会', '', global.id)
    const methods = await create('实验方法', project.id)
    const child = await create('光遗传', project.id, methods.id)
    const importPaper = async (title: string, scope = '') => {
      const response = await page.request.post(`${base}/api/v1/imports/bibliography${scope}`, { multipart: { files: { name: 'sidebar.bib', mimeType: 'application/x-bibtex', buffer: Buffer.from(`@article{${title},title={${title}},author={Sidebar Test},year={2026}}`) } } })
      expect(response.ok(), await response.text()).toBe(true)
    }
    await importPaper('Loose')
    await importPaper('GlobalCategory', `?collection_id=${globalChild.id}`)
    await importPaper('ProjectOnly', `?project_id=${project.id}`)
    await importPaper('ProjectCategory', `?project_id=${project.id}&collection_id=${child.id}`)
    await page.reload()
    await page.getByTestId('activity-literature').click()
    const view = (key: string) => sidebar.locator(`[data-sidebar-view="${key}"]`)
    await expect(view('all').locator('.lit-count')).toHaveText('4')
    await expect(view('unorganized').locator('.lit-count')).toHaveText('1')
    await view('unorganized').hover()
    await expect(page.getByRole('tooltip')).toHaveCount(0)
    await expect(sidebar.locator('[data-sidebar-view] svg')).toHaveCount(0)
    await expect(sidebar.locator('[data-sidebar-project] .lit-nav-row svg')).toHaveCount(0)
    await expect(sidebar.getByText('已关联至项目', { exact: true })).toBeVisible()
    await expect(sidebar.getByRole('button', { name: '搜索标签', exact: true })).toBeVisible()
    await expect(sidebar.getByRole('button', { name: '新建标签', exact: true })).toHaveCount(1)
    const response = page.waitForResponse(r => r.url().includes('/api/v1/literatures?') && r.url().includes('without_project=true'))
    await view('unorganized').click()
    expect((await (await response).json()).items.map((item: { title: string }) => item.title)).toEqual(['Loose'])
    await view('all').click()
    await sidebar.getByRole('button', { name: '展开「会后」里的子分类', exact: true }).click()
    await sidebar.getByRole('button', { name: '展开「测试091803」里的分类', exact: true }).click()
    await sidebar.getByRole('button', { name: '展开「实验方法」里的子分类', exact: true }).click()
    const x = async (locator: Locator) => (await locator.boundingBox())!.x
    const allX = await x(view('all').locator('.lit-nav-name'))
    const countEdge = async (locator: Locator) => { const box = await locator.boundingBox(); return box!.x + box!.width }
    const rightEdge = await countEdge(view('all').locator('.lit-count'))
    expect(await countEdge(view('recent').locator('.lit-count'))).toBe(rightEdge)
    expect(await countEdge(view('unorganized').locator('.lit-count'))).toBe(rightEdge)
    expect(Math.abs(await countEdge(sidebar.getByTestId(`literature-collection-${global.id}`).locator('.lit-count')) - rightEdge)).toBeLessThanOrEqual(1)
    expect(await x(view('recent').locator('.lit-nav-name'))).toBe(allX)
    expect(await x(view('unorganized').locator('.lit-nav-name'))).toBe(allX)
    expect(await x(sidebar.getByText('会后', { exact: true }))).toBeGreaterThan(allX)
    expect(await x(sidebar.getByTestId(`literature-collection-${globalChild.id}`)) - await x(sidebar.getByTestId(`literature-collection-${global.id}`))).toBe(16)
    expect(await x(sidebar.getByTestId(`literature-collection-${methods.id}`)) - await x(sidebar.locator(`[data-sidebar-project="${project.id}"]`))).toBe(16)
    expect(await x(sidebar.getByTestId(`literature-collection-${child.id}`)) - await x(sidebar.getByTestId(`literature-collection-${methods.id}`))).toBe(16)
    expect((await view('all').boundingBox())!.height).toBe((await sidebar.getByTestId(`literature-collection-${child.id}`).boundingBox())!.height)
    const categoryY = (await sidebar.locator('[data-ob="literature-categories"]').boundingBox())!.y
    expect((await sidebar.locator('[data-ob="literature-project-categories"]').boundingBox())!.y).toBeGreaterThan(categoryY)
    await page.mouse.move(600, 70)
    await page.screenshot({ path: join(evidence, 'global-nested.png') })
    await sidebar.getByRole('button', { name: '收起我的分类', exact: true }).click()
    await expect(sidebar.getByText('会后', { exact: true })).toHaveCount(0)
    await expect(sidebar.getByText('光遗传', { exact: true })).toBeVisible()
    await sidebar.getByRole('button', { name: '收起已关联至项目', exact: true }).click()
    await sidebar.getByRole('button', { name: '收起标签', exact: true }).click()
    await sidebar.getByRole('button', { name: '收起我的文献', exact: true }).click()
    await page.reload()
    await page.getByTestId('activity-literature').click()
    await expect(sidebar.getByRole('button', { name: '展开我的文献', exact: true })).toBeVisible()
    await sidebar.getByRole('button', { name: '展开我的文献', exact: true }).click()
    await expect(sidebar.getByRole('button', { name: '展开我的分类', exact: true })).toBeVisible()
    await expect(sidebar.getByRole('button', { name: '展开已关联至项目', exact: true })).toBeVisible()
    await expect(sidebar.getByRole('button', { name: '展开标签', exact: true })).toBeVisible()
    await sidebar.getByRole('button', { name: '展开我的分类', exact: true }).click()
    await sidebar.getByRole('button', { name: '展开已关联至项目', exact: true }).click()
    await expect(sidebar.getByText('9 月组会', { exact: true })).toBeVisible()
    await expect(sidebar.getByText('光遗传', { exact: true })).toBeVisible()
    await page.getByTestId('topbar-project').click()
    await page.getByTestId('project-menu-option-测试091803').click()
    await page.getByTestId('activity-literature').click()
    await expect(sidebar.getByText('本项目文献', { exact: true })).toBeVisible()
    await expect(sidebar.locator('[data-ob="literature-project-categories"]')).toHaveCount(0)
    await expect(view('all').locator('.lit-count')).toHaveText('2')
    await expect(view('unorganized').locator('.lit-count')).toHaveText('1')
    await expect(sidebar.getByText('光遗传', { exact: true })).toBeVisible()
    expect(await x(sidebar.getByText('实验方法', { exact: true }))).toBeGreaterThan(await x(view('all').locator('.lit-nav-name')))
    await page.screenshot({ path: join(evidence, 'project-nested.png') })
    await sidebar.getByText('光遗传', { exact: true }).click()
    await expect(sidebar.getByTestId(`literature-collection-${child.id}`)).toHaveClass(/is-active/)
    await view('unorganized').click()
    const projectItems = await (await page.request.get(`${base}/api/v1/literatures?project_id=${project.id}&without_collection=true`)).json()
    expect(projectItems.items.map((item: { title: string }) => item.title)).toEqual(['ProjectOnly'])
    desktop.assertNoPageErrors()
  } finally {
    await desktop.attachArtifacts()
  }
})
