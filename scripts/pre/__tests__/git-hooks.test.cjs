const sourceDirectory = require('node:path').dirname(__dirname)
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
test('legacy hook entry leaves shared hooks and third-party contents unchanged', context => {
  const repo = fs.mkdtempSync(path.join(os.tmpdir(), 'hooks-'))
  context.after(() => fs.rmSync(repo, { recursive: true, force: true }))
  execFileSync('git', ['init', '-q', repo])
  fs.mkdirSync(path.join(repo, 'scripts/pre'), { recursive: true })
  fs.copyFileSync(path.join(sourceDirectory, 'install-git-hooks.sh'), path.join(repo, 'scripts/pre/install-git-hooks.sh'))
  const hook = path.join(repo, '.git/hooks/post-checkout')
  const content = '#!/bin/sh\necho third-party\n# scholarseed-symlink-fix\necho legacy\n'
  fs.writeFileSync(hook, content)
  execFileSync('bash', [path.join(repo, 'scripts/pre/install-git-hooks.sh')], { cwd: repo })
  assert.equal(fs.readFileSync(hook, 'utf8'), content)
  assert.equal(fs.existsSync(path.join(repo, '.git/hooks/post-merge')), false)
})
